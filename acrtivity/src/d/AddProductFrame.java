    private void jLabel1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel1MouseClicked
  System.out.println("--- STARTING ADD PROCESS ---");
    
    String name = txtName.getText();
    String price = txtPrice.getText();
    String qty = txtQty.getText();
    String status = cmbStatus.getSelectedItem().toString();

    try {
        Connection con = DBC.connectDB();
        
        // DEBUG: Print what we are sending
        System.out.println("Inserting: " + name + " | " + price + " | " + qty);

        String sql = "INSERT INTO Tbl_product (p_name, p_price, p_qty, p_status) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = con.prepareStatement(sql);
        
        pst.setString(1, name);
        pst.setString(2, price); // Note: SQLite allows saving text as numbers, this is safer for testing
        pst.setString(3, qty);
        pst.setString(4, status);
        
        int rows = pst.executeUpdate(); // This executes the save
        
        if (rows > 0) {
            System.out.println("SUCCESS: Database reported 1 row added.");
            javax.swing.JOptionPane.showMessageDialog(this, "Saved! Check your database now.");
        } else {
            System.out.println("FAIL: Database reported 0 rows added.");
        }
        
        con.close();
        this.dispose();

    } catch (Exception e) {
        // THIS IS THE IMPORTANT PART
        System.out.println("CRITICAL ERROR: " + e.getMessage());
        e.printStackTrace(); // Prints the full red error in output
        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jLabel1MouseClicked

