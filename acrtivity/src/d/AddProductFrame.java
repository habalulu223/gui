    private void txtQtyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtQtyActionPerformed
        String input = txtQty.getText();
    
    // 1. Check if the field is empty (Allow empty so they can backspace)
    if(input.isEmpty()) {
        return;
    }

    // 2. CHECK IF INPUT IS A NUMBER
    // The regex "[0-9]+" means "only digits allowed"
    if (!input.matches("[0-9]+")) {
        
        // A. Show Error Message
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Invalid Input! Quantity must be a number.", 
            "Error", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
        
        // B. Reset to Default "1"
        txtQty.setText("1");
    }
    }//GEN-LAST:event_txtQtyActionPerformed

